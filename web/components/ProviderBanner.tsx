import { transcriptionProviderInfo } from '@/lib/transcription';
import { llmProviderInfo } from '@/lib/llm';

/** Tells the user plainly when demo/rule-based providers are active or keys are missing. */
export default function ProviderBanner() {
  const t = transcriptionProviderInfo();
  const a = llmProviderInfo();
  const msgs: React.ReactNode[] = [];
  if (!t.ready) msgs.push(<>Transcription provider <b>{t.id}</b> is not configured ({t.problem}). Server transcription will fail until it is set.</>);
  else if (t.isDemo)
    msgs.push(
      <>
        <b>Demo transcription is active.</b> Server-side transcription does not listen to your audio; it inserts a scripted sample conversation so you can test the flow. Set <code>TRANSCRIPTION_PROVIDER</code> to <code>groq</code>, <code>openai</code> or <code>deepgram</code> with an API key for real transcripts. Offline meetings can also use your browser&apos;s built-in speech recognition.
      </>,
    );
  if (!a.ready) msgs.push(<>AI provider <b>{a.id}</b> is not configured ({a.problem}); notes will use the rule-based extractor.</>);
  else if (a.isHeuristic) msgs.push(<>Notes are generated by the <b>rule-based extractor</b> (no AI model configured). Set <code>LLM_PROVIDER</code> to <code>groq</code>, <code>anthropic</code> or <code>openai</code> for AI notes.</>);
  if (!msgs.length) return null;
  return (
    <div className="alert warn small" data-testid="provider-banner">
      {msgs.map((m, i) => <div key={i} style={{ marginTop: i ? 6 : 0 }}>{m}</div>)}
    </div>
  );
}
